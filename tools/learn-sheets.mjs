#!/usr/bin/env node
/*  Regenerates supabase/functions/api/seed-sheets.js: which sheets each
 *  action reads, learned by running the test flows through the engine.
 *
 *      node tools/learn-sheets.mjs
 *
 *  A fresh Edge Function instance uses it to load everything an action
 *  needs in one round trip instead of discovering sheets one at a time.
 *  Purely a speed-up: a stale or missing entry costs a round trip or two,
 *  never a wrong answer, because the engine still discovers and remembers.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { createHarness } = require(path.join(root, 'tests', 'engine', 'lib', 'harness.js'));
const { FLOWS } = require(path.join(root, 'tests', 'engine', 'lib', 'flows.js'));

const seen = new Map();
for (const flow of FLOWS) {
  let engine = null;
  const { H } = await flow.run(async (opts) => { const h = await createHarness(opts); engine = h.engine; return h; });
  if (H.failures.length) { console.error('flow "' + flow.title + '" disagreed with the model; fix that first'); process.exit(1); }
  for (const [key, sheets] of engine.learned) {
    if (!seen.has(key)) seen.set(key, new Set());
    for (const s of sheets) seen.get(key).add(s);
  }
}
const seed = {};
for (const key of [...seen.keys()].sort()) seed[key] = [...seen.get(key)].sort();

writeFileSync(path.join(root, 'supabase', 'functions', 'api', 'seed-sheets.js'),
  '/* GENERATED by tools/learn-sheets.mjs: the sheets each action reads, so a fresh\n' +
  '   instance loads them in one go. A speed-up only; safe to be out of date. */\n' +
  'export const SEED_SHEETS = ' + JSON.stringify(seed, null, 1).replace(/\n\s*/g, ' ') + ';\n');
console.log('seed-sheets.js: ' + Object.keys(seed).length + ' actions');
