#!/usr/bin/env node
/*  Regenerates supabase/functions/api/backend.js from sumo-fantasy.gs.
 *
 *  The Edge Function can't read a .gs file off disk once deployed, so it
 *  imports the source as a string. Run this after every edit to the .gs:
 *
 *      node tools/build-backend.mjs
 *
 *  tests/run.sh fails while backend.js is stale, so a forgotten build can't
 *  ship quietly. It refuses to build from an empty .gs; an empty commit of
 *  that file has happened once already (cf2852b, 2026-10-20).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const gs = path.join(root, 'sumo-fantasy.gs');
const out = path.join(root, 'supabase', 'functions', 'api', 'backend.js');

const src = readFileSync(gs, 'utf8');
if (src.trim().length < 1000 || !/function doGet\(/.test(src) || !/function doPost\(/.test(src)) {
  console.error('sumo-fantasy.gs looks empty or truncated (' + src.length + ' chars). Not building.');
  process.exit(1);
}
const sha = createHash('sha256').update(src).digest('hex');
const version = (src.match(/var BACKEND_VERSION = '([^']*)'/) || [])[1] || '?';

writeFileSync(out,
  '/* GENERATED by tools/build-backend.mjs from sumo-fantasy.gs. Do not edit by hand:\n' +
  '   edit sumo-fantasy.gs, then run `node tools/build-backend.mjs`. */\n' +
  'export const SOURCE_SHA256 = ' + JSON.stringify(sha) + ';\n' +
  'export const SOURCE_VERSION = ' + JSON.stringify(version) + ';\n' +
  'export const SOURCE = ' + JSON.stringify(src) + ';\n');

console.log('backend.js <- sumo-fantasy.gs  (' + src.length + ' chars, BACKEND_VERSION ' + version + ', sha256 ' + sha.slice(0, 12) + ')');
